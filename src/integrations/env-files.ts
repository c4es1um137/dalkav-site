// Writes dist/_headers at the end of the build. Everything environment-specific
// comes from SITE_ENV via src/env.ts; there are no per-environment files.
import { writeFile } from 'node:fs/promises';
import type { AstroIntegration } from 'astro';
import { SECURITY_HEADERS } from '../config/security-headers';
import type { ResolvedEnv } from '../env';

export function renderHeaders(env: ResolvedEnv): string {
  const block = (pattern: string, headers: ReadonlyArray<readonly [string, string]>) =>
    [pattern, ...headers.map(([name, value]) => `  ${name}: ${value}`)].join('\n');

  // One block per pattern: a second "/*" block replaces the first in the Pages
  // parser instead of merging, so test's noindex joins the security headers here.
  const global: Array<readonly [string, string]> = [...SECURITY_HEADERS];
  if (env.isTest) global.push(['X-Robots-Tag', 'noindex, nofollow']);

  const blocks = [
    `# Generated by src/integrations/env-files.ts for SITE_ENV=${env.siteEnv}. Do not edit.`,
    block('/*', global),
    block('/_astro/*', [['Cache-Control', 'public, max-age=31536000, immutable']]),
    // *.pages.dev hostnames (production and per-deployment) are never indexed.
    block('https://:project.pages.dev/*', [['X-Robots-Tag', 'noindex']]),
    block('https://:version.:project.pages.dev/*', [['X-Robots-Tag', 'noindex']]),
  ];
  return blocks.join('\n\n') + '\n';
}

/** Writes dist/_headers at the end of the build, driven by SITE_ENV. */
export default function envFiles(env: ResolvedEnv): AstroIntegration {
  return {
    name: 'dalkav:env-files',
    hooks: {
      'astro:build:done': async ({ dir, logger }) => {
        await writeFile(new URL('_headers', dir), renderHeaders(env), 'utf8');
        logger.info(`_headers written for SITE_ENV=${env.siteEnv}`);
      },
    },
  };
}
